// Generates TypeScript types and Java records from protocol/schemas.
// This is the entry point: it reads and checks the schemas, then writes what typescript.ts and java.ts produce.
// Run it with "pnpm protocol:gen"; "pnpm protocol:check" fails when the generated code is stale.
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { join, relative } from "node:path";
import { JAVA_DIR, javaFiles } from "./java.ts";
import { typescriptFile } from "./typescript.ts";

export const PROTOCOL_DIR = join(import.meta.dirname, "..");
const REPO_DIR = join(PROTOCOL_DIR, "..");
export const SCHEMAS_DIR = join(PROTOCOL_DIR, "schemas");
const TS_DIR = join(PROTOCOL_DIR, "generated");
export const NOTICE =
  "Generated by pnpm protocol:gen from protocol/schemas. Do not edit.";
/** Schemas that are not messages: the shared types and the envelope. */
const NOT_MESSAGES = new Set(["common.schema.json", "envelope.schema.json"]);

export type Direction = "client" | "server";

export interface Schema {
  title?: string;
  "x-message"?: { type: string; direction: Direction };
  [keyword: string]: unknown;
}

export interface Message {
  type: string;
  direction: Direction;
  file: string;
  schema: Schema;
}

export interface Version {
  current: number;
  minSupported: number;
}

function readJson<T>(path: string): T {
  return JSON.parse(readFileSync(path, "utf8")) as T;
}

/** Reads version.json and checks that 1 <= minSupported <= current. */
export function readVersion(): Version {
  const version = readJson<Version>(join(PROTOCOL_DIR, "version.json"));
  if (
    !Number.isInteger(version.current) ||
    !Number.isInteger(version.minSupported)
  ) {
    throw new Error("version.json: current and minSupported must be integers");
  }
  if (version.minSupported < 1 || version.minSupported > version.current) {
    throw new Error("version.json: expected 1 <= minSupported <= current");
  }
  return version;
}

/** The file name form of a message type: playerJoined becomes player-joined. */
export function kebabCase(type: string): string {
  return type.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

/** Checks the x-message block of one schema file and turns it into a Message. */
export function toMessage(file: string, schema: Schema): Message {
  const meta = schema["x-message"];
  if (!meta) {
    throw new Error(`${file}: missing "x-message"`);
  }
  if (!/^[a-z][a-zA-Z0-9]*$/.test(meta.type)) {
    throw new Error(`${file}: type "${meta.type}" is not camelCase`);
  }
  const expected = `${kebabCase(meta.type)}.schema.json`;
  if (file !== expected) {
    throw new Error(`${file}: expected the file name ${expected}`);
  }
  if (meta.direction !== "client" && meta.direction !== "server") {
    throw new Error(`${file}: direction must be "client" or "server"`);
  }
  if (!schema.title || !/^[A-Z][A-Za-z0-9]*$/.test(schema.title)) {
    throw new Error(`${file}: title must be PascalCase`);
  }
  return { type: meta.type, direction: meta.direction, file, schema };
}

/** Every message schema, sorted by file name so that the output is always the same. */
export function readMessages(): Message[] {
  return readdirSync(SCHEMAS_DIR)
    .filter((file) => file.endsWith(".schema.json") && !NOT_MESSAGES.has(file))
    .sort()
    .map((file) => toMessage(file, readJson<Schema>(join(SCHEMAS_DIR, file))));
}

export function byDirection(
  messages: Message[],
  direction: Direction,
): Message[] {
  return messages.filter((message) => message.direction === direction);
}

/** The name of a message's payload type: Hello becomes HelloPayload. */
export function payloadName(message: Message): string {
  return `${message.schema.title}Payload`;
}

/** The shared types of common.schema.json, by name. */
export function readCommonTypes(): Record<string, Schema> {
  const common = readJson<{ $defs: Record<string, Schema> }>(
    join(SCHEMAS_DIR, "common.schema.json"),
  );
  return common.$defs;
}

/** Replaces the whole content of a directory that only the generator writes. */
function replaceDirectory(dir: string, files: Map<string, string>): void {
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  for (const [name, content] of files) {
    writeFileSync(join(dir, name), content);
  }
}

/** What differs between a generated directory on disk and what the generator would write. */
export function compareDirectory(
  dir: string,
  files: Map<string, string>,
): string[] {
  const shown = (name: string): string =>
    relative(REPO_DIR, join(dir, name)).replaceAll("\\", "/");
  const problems: string[] = [];
  for (const [name, content] of files) {
    const path = join(dir, name);
    if (!existsSync(path)) {
      problems.push(`missing: ${shown(name)}`);
    } else if (
      readFileSync(path, "utf8").replaceAll("\r\n", "\n") !== content
    ) {
      problems.push(`changed: ${shown(name)}`);
    }
  }
  const onDisk = existsSync(dir) ? readdirSync(dir).sort() : [];
  for (const name of onDisk) {
    if (!files.has(name)) {
      problems.push(`not generated: ${shown(name)}`);
    }
  }
  return problems;
}

function printSummary(version: Version, messages: Message[]): void {
  console.log(
    `Protocol version ${version.current} (min supported ${version.minSupported})`,
  );
  for (const direction of ["client", "server"] as const) {
    const types = byDirection(messages, direction).map(
      (message) => message.type,
    );
    console.log(`${direction}: ${types.join(", ")}`);
  }
}

/** Every generated directory, with the files the generator writes in it. */
async function generate(
  version: Version,
  messages: Message[],
): Promise<Map<string, Map<string, string>>> {
  const typescript = await typescriptFile(version, messages);
  return new Map([
    [TS_DIR, new Map([["index.ts", typescript]])],
    [JAVA_DIR, javaFiles(version, messages, readCommonTypes())],
  ]);
}

/** Writes the generated code, or with --check only compares it with the files on disk. */
async function main(): Promise<void> {
  try {
    const version = readVersion();
    const messages = readMessages();
    const outputs = await generate(version, messages);
    if (!process.argv.includes("--check")) {
      for (const [dir, files] of outputs) {
        replaceDirectory(dir, files);
      }
      printSummary(version, messages);
      return;
    }
    const problems = [...outputs].flatMap(([dir, files]) =>
      compareDirectory(dir, files),
    );
    if (problems.length === 0) {
      console.log("Generated code is up to date.");
      return;
    }
    console.error(
      'Generated code is out of date. Run "pnpm protocol:gen" and commit the result.',
    );
    for (const problem of problems) {
      console.error(`  ${problem}`);
    }
    process.exitCode = 1;
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}

// Runs only when the file is executed, not when a test imports it.
if (import.meta.main) {
  await main();
}
